/**
 * Copies prisma/migrations/*\/migration.sql into src/generated/migrations.ts, so the app can
 * create its tables at runtime without reading files from disk (see src/instrumentation.ts).
 * Runs after `prisma generate` on every install.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const dir = join(root, "prisma", "migrations");
const migrations = readdirSync(dir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => ({ name: e.name, sql: readFileSync(join(dir, e.name, "migration.sql"), "utf8") }))
  .sort((a, b) => a.name.localeCompare(b.name));

mkdirSync(join(root, "src", "generated"), { recursive: true });
writeFileSync(
  join(root, "src", "generated", "migrations.ts"),
  `// Generated by prisma/bundle-migrations.ts. Do not edit.\nimport type { Migration } from "@/lib/apply-migrations";\n\nexport const MIGRATIONS: Migration[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`Bundled ${migrations.length} migration(s) into src/generated/migrations.ts`);
